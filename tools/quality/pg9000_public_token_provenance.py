"""Classify only all-exact public artifact/Java token digests; original findings unchanged."""
from collections import Counter
import datetime as dt
import json
from pathlib import Path
import re
from host_tool_invocation import capture,verify
from public_blob_scan import sha
from public_java_digest_provenance import captures,digests,proven_set

ROOT=Path(__file__).resolve().parents[2]
BASE=ROOT/'evidence/01_PT/018_NK-OPS-001/evidence/provisional'
SCAN=BASE/'PG8968-public-blob-scan-v1'
PRIOR=BASE/'PG8980-public-finding-provenance-v1'
ANCESTOR=BASE/'PG8990-public-ancestor-provenance-v1'
SNAPSHOT=ROOT.parent/'pgpt-runs/PG379/pg8968-public-blob-scan-v1/tracked'
OUT=BASE/'PG9000-public-token-provenance-v1'
REFERENCE=ROOT/'tools/quality/pg6542_jdbc_catch_inventory.py'
REFERENCE_SHA='9be2472be16788ab9babb537d01b84f47010ba65e31022184070457d6052dcb4'


def key(row):return tuple(row[name] for name in ('path','ruleId','startLine','endLine','inputSha256'))


def main():
    invocation=capture(Path(__file__));assert not OUT.exists() and sha(REFERENCE.read_bytes())==REFERENCE_SHA
    # Literal token-array oracle, not generated by the subject digest function.
    golden='try {} catch(SQLException failure) { throw failure; }'
    assert digests(golden)==[dict(catchLine=1,publicTokenDigest=sha(b'["throw", "failure", ";"]'))]
    assert digests('// catch(SQLException fake) {}\nString s="catch(SQLException fake) {}";')==[]
    literal='catch(SQLException e) { log("fictitious value"); throw e; }'
    assert digests(literal)[0]['publicTokenDigest']==sha(b'["log", "(", "LITERAL", ")", ";", "throw", "e", ";"]')
    rejected=[]
    for name,text in [('open-header','catch(SQLException x'),('open-body','catch(SQLException x) {'),('no-body','catch(SQLException x) x')]:
        try:digests(text)
        except ValueError:rejected.append(name)
        else:raise AssertionError('malformed source accepted')
    public={sha(b'public A'):dict(public='A'),sha(b'public B'):dict(public='B')}
    assert proven_set(set(public),public)==[public[value] for value in sorted(public)]
    assert proven_set({next(iter(public)),sha(b'unknown')},public) is None and proven_set(set(),public) is None
    prior=json.loads((PRIOR/'manifest.json').read_bytes());ancestor=json.loads((ANCESTOR/'manifest.json').read_bytes())
    assert prior['actualExit']==ancestor['actualExit']==0 and prior['source']==ancestor['source']=='fb9fce0f91de3d9fdfa634fe277592700f915e45'
    assert sha((PRIOR/'classifications.json').read_bytes())==prior['classificationSha256']
    assert sha((ANCESTOR/'updates.json').read_bytes())==ancestor['updatesSha256']
    already=Counter(key(row) for row in json.loads((ANCESTOR/'updates.json').read_bytes()))
    pending=[]
    for row in json.loads((PRIOR/'classifications.json').read_bytes()):
        if row['disposition']!='UNCLASSIFIED':continue
        identifier=key(row)
        if already[identifier]>0:already[identifier]-=1
        else:pending.append(row)
    assert len(pending)==9960 and sum(already.values())==0
    inventory=json.loads((SCAN/'inventory.json').read_bytes())['rows']
    proofs={}
    for row in sorted(inventory,key=lambda row:row['path']):
        proofs.setdefault(row['sha256'],dict(proofKind='CURRENT_PUBLIC_BLOB',path=row['path'],sha256=row['sha256'],gitObject=row['gitObject']))
    for proof in json.loads((ANCESTOR/'public-proofs.json').read_bytes()):
        proofs.setdefault(proof['sha256'],proof)
    java_sources=0;catch_sites=0
    for row in inventory:
        name=row['path']
        if not name.startswith('src/') or '/src/main/java/' not in name or not name.endswith('.java'):continue
        data=(SNAPSHOT/name).read_bytes();assert sha(data)==row['sha256'];java_sources+=1
        for site in digests(data.decode('utf-8')):
            catch_sites+=1
            digest=site['publicTokenDigest']
            proofs.setdefault(digest,dict(proofKind='PUBLIC_JAVA_SQLCATCH_TOKEN_DIGEST',path=name,
                sourceSha256=row['sha256'],gitObject=row['gitObject'],catchLine=site['catchLine'],
                publicTokenDigest=digest,normalizationReferenceSha256=REFERENCE_SHA))
    rules=json.loads((BASE/'PG8979-gitleaks-rule-provenance-v1/manifest.json').read_bytes())['rules']
    compiled={name:re.compile(rule['regex'],re.ASCII) for name,rule in rules.items()}
    lines={};matches={};updates=[];unclassified=Counter();kinds=Counter()
    for row in pending:
        path=row['path']
        if path not in lines:
            data=(SNAPSHOT/path).read_bytes();assert sha(data)==row['inputSha256'];lines[path]=data.decode('utf-8').splitlines(keepends=True)
        identifier=key(row)
        if identifier not in matches:matches[identifier]=captures(lines[path],row,compiled[row['ruleId']])
        candidates=matches[identifier]
        bound=proven_set(candidates,proofs)
        if bound is None:
            unclassified['NO_EXACT_CAPTURE' if not candidates else 'AT_LEAST_ONE_CAPTURE_WITHOUT_PUBLIC_PROOF']+=1
            continue
        original={name:row[name] for name in ('path','ruleId','startLine','endLine','inputSha256')}
        types=sorted({proof['proofKind'] for proof in bound})
        kinds['ALL_CAPTURES_'+('_'.join(types))]+=1
        updates.append(dict(**original,disposition='FALSE_POSITIVE_ALL_EXACT_CAPTURES_PUBLIC_DIGESTS',
             reason='EVERY_EXACT_CAPTURE_BOUND_TO_ACTUAL_PUBLIC_ARTIFACT_OR_DOCUMENTED_PUBLIC_SOURCE_TRANSFORM',
             priorDisposition='UNCLASSIFIED',exactCaptureCount=len(candidates),publicArtifactProofs=bound))
    assert len(updates)+sum(unclassified.values())==9960
    verify(invocation);OUT.mkdir()
    with (OUT/'updates.json').open('x',encoding='utf-8') as stream:
        json.dump(updates,stream,ensure_ascii=False,sort_keys=True,indent=2);stream.write('\n')
    value=dict(actualExit=0,timeUTC=dt.datetime.now(dt.timezone.utc).isoformat(),invocation=invocation,
       source=prior['source'],contentCommit=prior['contentCommit'],priorManifestSha256=sha((PRIOR/'manifest.json').read_bytes()),
       ancestorManifestSha256=sha((ANCESTOR/'manifest.json').read_bytes()),publicJavaSources=java_sources,
       publicSqlCatchSites=catch_sites,lexicalReferenceSha256=REFERENCE_SHA,independentGoldenCases=6,
       rejectedMalformedSourceCases=rejected,originalResidual=9960,additionalFalsePositives=len(updates),
       cumulativeFalsePositiveProof=30126+len(updates),remainingUnclassified=sum(unclassified.values()),
       updateKinds=dict(kinds),remainingReasons=dict(unclassified),updatesSha256=sha((OUT/'updates.json').read_bytes()),
       originalFindingMultiplicityPreserved=True,rawCandidatesOrSecretHashesPersisted=False,scannerRerun=False,
       ancestorWholeHashRerun=False,productTestsExecuted=0,productCoverage=None,whole451SecretGateAccepted=False,
       formalUpdated=False,newAccepted=0)
    with (OUT/'manifest.json').open('x',encoding='utf-8') as stream:
        json.dump(value,stream,ensure_ascii=False,sort_keys=True,indent=2);stream.write('\n')
    print(json.dumps({name:value[name] for name in ('actualExit','publicJavaSources','publicSqlCatchSites','additionalFalsePositives','cumulativeFalsePositiveProof','remainingUnclassified','updateKinds')}))


if __name__=='__main__':main()
