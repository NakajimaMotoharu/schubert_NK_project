    proof = data.read_checked(data.BASE/'PG11354-api-web-source-guard-post-v1/manifest.json',
        '3928e5796bb3c0b79bdfed1afe720678ce18096ce0a9a9b514acd3c6c9492d26')
    plan = data.read_checked(data.BASE/'PG11344-api-web-source-guard-plan-v1/manifest.json',
        '82dadcf32291197184759d2a2583ccf54ad2bd78d95a2174c1d5b78341006680')
    normal = data.read_checked(data.BASE/'PG11348-api-web-source-guard-six-compile-v1/manifest.json',
        '46569de89d536e303184cd570d83f5138eb3a344abeb64f4e01160622a5482e8')
    assert proof['actualExit'] == normal['actualExit'] == 0 and proof['source'] == normal['source'] == SOURCE
    assert all(data.sha((data.ROOT/p).read_bytes()) == h for p,h in normal['begin']['inputHashes'].items())

