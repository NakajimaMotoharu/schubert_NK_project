package dev.codex.schubert.nk.web.bootstrap;

import dev.codex.schubert.nk.web.logging.WebSecurityAudit;
import dev.codex.schubert.nk.web.messaging.JmsContextFactory;
import dev.codex.schubert.nk.web.security.MqAuthenticationProvider;
import dev.codex.schubert.nk.web.security.WebSecurityFilterFactory;
import dev.codex.schubert.nk.web.session.EncryptedWebSessionRepository;
import dev.codex.schubert.nk.web.session.SessionPayloadCodec;
import dev.codex.schubert.nk.web.session.SpringEncryptedSessionRepository;
import java.nio.file.Path;
import java.time.Clock;
import java.util.Map;
import java.util.Objects;
import java.util.UUID;
import java.util.function.BiFunction;
import java.util.function.Consumer;
import java.util.function.Function;
import java.util.function.Supplier;
import javax.sql.DataSource;
import org.apache.catalina.LifecycleException;
import org.jspecify.annotations.Nullable;

/**
 * Restricted production Web composition: DB/JMS transport readiness precedes HTTP binding, then the
 * approved encrypted-session security chain owns all requests. The caller owns every supplied
 * dependency and the returned server; credential loading, broker management readiness, API dispatch
 * and NK Characterization are separate startup gates. NK-WEB-002;
 * SYS-001/002/004,AUT-001,MQ-001/002; UI211/212/226/252; SS311/314/321/342/352/362;
 * PG222/PT-SCR117..119.
 */
public final class WebApplication {
  private final DataSource database;
  private final JmsContextFactory broker;
  private final SessionPayloadCodec codec;
  private final Clock clock;
  private final MqAuthenticationProvider authentication;
  private final WebSecurityAudit audit;
  private final Supplier<UUID> requestIds;

  public WebApplication(
      DataSource database,
      JmsContextFactory broker,
      SessionPayloadCodec codec,
      Clock clock,
      MqAuthenticationProvider authentication,
      WebSecurityAudit audit,
      Supplier<UUID> requestIds) {
    this.database = Objects.requireNonNull(database, "database");
    this.broker = Objects.requireNonNull(broker, "broker");
    this.codec = Objects.requireNonNull(codec, "codec");
    this.clock = Objects.requireNonNull(clock, "clock");
    this.authentication = Objects.requireNonNull(authentication, "authentication");
    this.audit = Objects.requireNonNull(audit, "audit");
    this.requestIds = Objects.requireNonNull(requestIds, "requestIds");
  }

  public WebHttpServer start(Path runtimeDirectory, int port, Class<?>... featureConfigurations)
      throws LifecycleException {
    return start(runtimeDirectory, port, Map.of(), featureConfigurations);
  }

  public WebHttpServer start(
      Path runtimeDirectory,
      int port,
      Map<Class<?>, ?> dependencies,
      Class<?>... featureConfigurations)
      throws LifecycleException {
    // Validate the local path/port/configuration before borrowing DB or broker resources.
    WebHttpServer.validateConfiguration(runtimeDirectory, port, featureConfigurations);
    Map<Class<?>, ?> registeredDependencies = WebHttpServer.checkedDependencies(dependencies);
    return startWithValidatedDependencies(
        runtimeDirectory, port, ignored -> registeredDependencies, featureConfigurations);
  }

  /**
   * Supplies the exact repository used by the security filter to caller-owned MVC ports. This is
   * required by the API-session-invalid handler, whose identity check rejects a second repository
   * instance even when it points to the same database. Trace: AUT-002; UI225/226; SS313/314/352;
   * PG230/PT-SCR124..126.
   */
  public WebHttpServer startWithSessionDependencies(
      Path runtimeDirectory,
      int port,
      Function<SpringEncryptedSessionRepository, Map<Class<?>, ?>> dependencies,
      Class<?>... featureConfigurations)
      throws LifecycleException {
    WebHttpServer.validateConfiguration(runtimeDirectory, port, featureConfigurations);
    Objects.requireNonNull(dependencies, "dependencies");
    return startWithValidatedDependencies(
        runtimeDirectory, port, dependencies, featureConfigurations);
  }

  /**
   * Supplies one core/Spring pair to native token and Logout ports. No second encrypted repository
   * is generated by a feature callback. NK-WEB-002/AUT002004; UI224226232; SS313314342352;
   * PG-D369/NATIVE-CORE001002.
   */
  public WebHttpServer startWithCoreSessionDependencies(
      Path runtimeDirectory,
      int port,
      BiFunction<EncryptedWebSessionRepository, SpringEncryptedSessionRepository, Map<Class<?>, ?>>
          dependencies,
      Class<?>... featureConfigurations)
      throws LifecycleException {
    WebHttpServer.validateConfiguration(runtimeDirectory, port, featureConfigurations);
    Objects.requireNonNull(dependencies, "dependencies");
    return startWithCoreValidatedDependencies(
        runtimeDirectory, port, dependencies, featureConfigurations);
  }

  private WebHttpServer startWithValidatedDependencies(
      Path runtimeDirectory,
      int port,
      Function<SpringEncryptedSessionRepository, Map<Class<?>, ?>> dependencies,
      Class<?>... featureConfigurations)
      throws LifecycleException {
    return startWithCoreValidatedDependencies(
        runtimeDirectory,
        port,
        (core, sessions) -> dependencies.apply(sessions),
        featureConfigurations);
  }

  private WebHttpServer startWithCoreValidatedDependencies(
      Path runtimeDirectory,
      int port,
      BiFunction<EncryptedWebSessionRepository, SpringEncryptedSessionRepository, Map<Class<?>, ?>>
          dependencies,
      Class<?>... featureConfigurations)
      throws LifecycleException {
    return startCore(runtimeDirectory, port, dependencies, null, featureConfigurations);
  }

  /** Same pair and security chain, with partial HTTP ownership retained by the native caller. */
  WebHttpServer startOwnedWithCoreSessionDependencies(
      Path runtimeDirectory,
      int port,
      BiFunction<EncryptedWebSessionRepository, SpringEncryptedSessionRepository, Map<Class<?>, ?>>
          dependencies,
      Consumer<WebHttpServer> owner,
      Class<?>... featureConfigurations)
      throws LifecycleException {
    WebHttpServer.validateConfiguration(runtimeDirectory, port, featureConfigurations);
    Objects.requireNonNull(dependencies, "dependencies");
    Objects.requireNonNull(owner, "HTTP owner");
    return startCore(runtimeDirectory, port, dependencies, owner, featureConfigurations);
  }

  private WebHttpServer startCore(
      Path runtimeDirectory,
      int port,
      BiFunction<EncryptedWebSessionRepository, SpringEncryptedSessionRepository, Map<Class<?>, ?>>
          dependencies,
      @Nullable Consumer<WebHttpServer> owner,
      Class<?>... featureConfigurations)
      throws LifecycleException {
    new WebDependencyReadiness(database, broker).verify();
    var core = new EncryptedWebSessionRepository(database, codec, clock);
    var sessions = new SpringEncryptedSessionRepository(core, clock);
    Map<Class<?>, ?> registeredDependencies =
        WebHttpServer.checkedDependencies(dependencies.apply(core, sessions));
    var security =
        new WebSecurityFilterFactory().create(sessions, authentication, audit, requestIds);
    if (owner == null) {
      return WebHttpServer.start(
          runtimeDirectory, port, security, registeredDependencies, featureConfigurations);
    }
    return WebHttpServer.startOwned(
        runtimeDirectory, port, security, registeredDependencies, owner, featureConfigurations);
  }
}
