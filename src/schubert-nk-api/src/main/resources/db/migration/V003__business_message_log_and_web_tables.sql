CREATE TABLE schubert.questions (
    id bigint GENERATED BY DEFAULT AS IDENTITY (MINVALUE 1 MAXVALUE 999999999999 NO CYCLE),
    receipt_id char(26) NOT NULL,
    owner_user_id bigint NOT NULL,
    body text NOT NULL,
    operation_token uuid NOT NULL,
    submitted_at timestamptz NOT NULL,
    is_deleted boolean NOT NULL DEFAULT false,
    deleted_at timestamptz,
    deleted_by bigint,
    version bigint NOT NULL DEFAULT 0,
    CONSTRAINT pk_questions PRIMARY KEY (id),
    CONSTRAINT uq_questions_receipt_id UNIQUE (receipt_id),
    CONSTRAINT uq_questions_owner_operation UNIQUE (owner_user_id, operation_token),
    CONSTRAINT fk_questions_app_users_owner_user_id FOREIGN KEY (owner_user_id)
        REFERENCES schubert.app_users (id) ON DELETE RESTRICT,
    CONSTRAINT fk_questions_app_users_deleted_by FOREIGN KEY (deleted_by)
        REFERENCES schubert.app_users (id) ON DELETE RESTRICT,
    CONSTRAINT ck_questions_id_n12 CHECK (id BETWEEN 1 AND 999999999999),
    CONSTRAINT ck_questions_receipt_id CHECK (receipt_id ~ '^[0-9A-HJKMNP-TV-Z]{26}$'),
    CONSTRAINT ck_questions_body_bytes CHECK (octet_length(body) BETWEEN 1 AND 4096),
    CONSTRAINT ck_questions_delete_triple CHECK (
        (NOT is_deleted AND deleted_at IS NULL AND deleted_by IS NULL)
        OR (is_deleted AND deleted_at IS NOT NULL AND deleted_by IS NOT NULL)),
    CONSTRAINT ck_questions_version_n9 CHECK (version BETWEEN 0 AND 999999999)
);

