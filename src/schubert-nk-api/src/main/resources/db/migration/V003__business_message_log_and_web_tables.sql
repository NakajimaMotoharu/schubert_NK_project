    CONSTRAINT ck_app_logs_action_bytes CHECK (octet_length(action) BETWEEN 1 AND 64),
    CONSTRAINT ck_app_logs_message_bytes CHECK (octet_length(message) BETWEEN 1 AND 512),
    CONSTRAINT ck_app_logs_request_uri_bytes CHECK (request_uri IS NULL OR octet_length(request_uri) <= 256),
    CONSTRAINT ck_app_logs_status_code CHECK (status_code IS NULL OR status_code BETWEEN 100 AND 599),
    CONSTRAINT ck_app_logs_duration_ms CHECK (duration_ms IS NULL OR duration_ms BETWEEN 0 AND 999999999),
    CONSTRAINT ck_app_logs_security_hold CHECK (security_hold_until IS NULL OR category = 'SECURITY'),
    CONSTRAINT ck_app_logs_details_object CHECK (jsonb_typeof(details) = 'object'),
    CONSTRAINT ck_app_logs_details_bytes CHECK (octet_length(details::text) <= 1024)
);

