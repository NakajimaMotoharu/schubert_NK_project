CREATE TABLE schubert.async_jobs (
    id bigint GENERATED BY DEFAULT AS IDENTITY (MINVALUE 1 MAXVALUE 999999999999 NO CYCLE),
    question_id bigint NOT NULL,
    owner_user_id bigint NOT NULL,
    state varchar(12) NOT NULL,
    message_id uuid NOT NULL,
    correlation_id uuid NOT NULL,
    processing_message_id uuid,
    received_at timestamptz NOT NULL,
    state_changed_at timestamptz NOT NULL,
    started_at timestamptz,
    completed_at timestamptz,
    error_at timestamptz,
    cancelled_at timestamptz,
    retry_count integer NOT NULL DEFAULT 0,
    last_error_code varchar(64),
    last_error_message varchar(256),
    version bigint NOT NULL DEFAULT 0,
    CONSTRAINT pk_async_jobs PRIMARY KEY (id),
    CONSTRAINT uq_async_jobs_question_id UNIQUE (question_id),
    CONSTRAINT uq_async_jobs_message_id UNIQUE (message_id),
    CONSTRAINT uq_async_jobs_processing_message_id UNIQUE (processing_message_id),
    CONSTRAINT fk_async_jobs_questions_question_id FOREIGN KEY (question_id)
        REFERENCES schubert.questions (id) ON DELETE CASCADE,
    CONSTRAINT fk_async_jobs_app_users_owner_user_id FOREIGN KEY (owner_user_id)
        REFERENCES schubert.app_users (id) ON DELETE RESTRICT,
    CONSTRAINT ck_async_jobs_id_n12 CHECK (id BETWEEN 1 AND 999999999999),
    CONSTRAINT ck_async_jobs_state CHECK (state IN ('RECEIVED', 'PROCESSING', 'COMPLETED', 'ERROR', 'CANCELLED')),
    CONSTRAINT ck_async_jobs_retry_count CHECK (retry_count BETWEEN 0 AND 3),
    CONSTRAINT ck_async_jobs_version_n9 CHECK (version BETWEEN 0 AND 999999999),
    CONSTRAINT ck_async_jobs_state_times CHECK (
        (state = 'RECEIVED' AND started_at IS NULL AND completed_at IS NULL AND error_at IS NULL
            AND cancelled_at IS NULL AND processing_message_id IS NULL)
        OR (state = 'PROCESSING' AND started_at IS NOT NULL AND completed_at IS NULL AND error_at IS NULL
            AND cancelled_at IS NULL AND processing_message_id IS NOT NULL)
        OR (state = 'COMPLETED' AND started_at IS NOT NULL AND completed_at IS NOT NULL AND error_at IS NULL
            AND cancelled_at IS NULL AND processing_message_id IS NOT NULL)
        OR (state = 'ERROR' AND started_at IS NOT NULL AND completed_at IS NULL AND error_at IS NOT NULL
            AND cancelled_at IS NULL AND processing_message_id IS NOT NULL)
        OR (state = 'CANCELLED' AND started_at IS NULL AND completed_at IS NULL AND error_at IS NULL
            AND cancelled_at IS NOT NULL AND processing_message_id IS NULL)),
    CONSTRAINT ck_async_jobs_error_pair CHECK (
        (state = 'ERROR' AND last_error_code IS NOT NULL AND last_error_message IS NOT NULL)
        OR (state <> 'ERROR' AND last_error_code IS NULL AND last_error_message IS NULL)),
    CONSTRAINT ck_async_jobs_time_order CHECK (
        received_at <= state_changed_at
        AND (started_at IS NULL OR received_at <= started_at)
        AND (completed_at IS NULL OR started_at <= completed_at)
        AND (error_at IS NULL OR started_at <= error_at)
        AND (cancelled_at IS NULL OR received_at <= cancelled_at))
);

CREATE TABLE schubert.notifications (
    id bigint GENERATED BY DEFAULT AS IDENTITY (MINVALUE 1 MAXVALUE 999999999999 NO CYCLE),
    job_id bigint NOT NULL,
    question_id bigint NOT NULL,
    owner_user_id bigint NOT NULL,
    notification_type varchar(12) NOT NULL,
    state varchar(12) NOT NULL,
    accepted_at timestamptz NOT NULL,
    state_changed_at timestamptz NOT NULL,
    error_code varchar(16),
    error_message varchar(512),
    created_at timestamptz NOT NULL,
    updated_at timestamptz NOT NULL,
    CONSTRAINT pk_notifications PRIMARY KEY (id),
    CONSTRAINT uq_notifications_job_id UNIQUE (job_id),
    CONSTRAINT fk_notifications_async_jobs_job_id FOREIGN KEY (job_id)
        REFERENCES schubert.async_jobs (id) ON DELETE RESTRICT,
    CONSTRAINT fk_notifications_questions_question_id FOREIGN KEY (question_id)
        REFERENCES schubert.questions (id) ON DELETE RESTRICT,
    CONSTRAINT fk_notifications_app_users_owner_user_id FOREIGN KEY (owner_user_id)
        REFERENCES schubert.app_users (id) ON DELETE RESTRICT,
    CONSTRAINT ck_notifications_id_n12 CHECK (id BETWEEN 1 AND 999999999999),
    CONSTRAINT ck_notifications_notification_type CHECK (notification_type IN ('ACCEPTED', 'COMPLETED', 'ERROR')),
    CONSTRAINT ck_notifications_state CHECK (state IN ('ACCEPTED', 'PROCESSING', 'COMPLETED', 'ERROR', 'CANCELLED')),
    CONSTRAINT ck_notifications_time_order CHECK (accepted_at <= state_changed_at),
    CONSTRAINT ck_notifications_error CHECK (
        (state = 'ERROR'
            AND error_code IN ('PROCESS_FAILED', 'SYSTEM_UNAVAIL', 'RESOURCE_LIMIT', 'DATA_INTEGRITY', 'PROTOCOL_ERROR')
            AND error_message IS NOT NULL)
        OR (state <> 'ERROR' AND error_code IS NULL AND error_message IS NULL))
);

CREATE TABLE schubert.request_inbox (
    message_id uuid NOT NULL,
    correlation_id uuid NOT NULL,
    request_layout_id char(8) NOT NULL,
    request_version char(3) NOT NULL,
    owner_user_id bigint,
    operation_token uuid,
    request_fingerprint_hmac char(64) NOT NULL,
    fingerprint_key_version varchar(16) NOT NULL,
    processing_state varchar(12) NOT NULL,
    result_ref_type varchar(16),
    result_ref_id bigint,
    result_ref_uuid uuid,
    response_layout_id char(8),
    response_version char(3),
    response_body_encrypted bytea,
    response_key_version varchar(16),
    created_at timestamptz NOT NULL,
    completed_at timestamptz,
    expires_at timestamptz NOT NULL,
    CONSTRAINT pk_request_inbox PRIMARY KEY (message_id),
    CONSTRAINT fk_request_inbox_app_users_owner_user_id FOREIGN KEY (owner_user_id)
        REFERENCES schubert.app_users (id) ON DELETE RESTRICT,
    CONSTRAINT ck_request_inbox_request_layout_id CHECK (request_layout_id ~ '^[A-Z0-9]{8}$'),
    CONSTRAINT ck_request_inbox_request_version CHECK (request_version ~ '^[0-9]{3}$'),
    CONSTRAINT ck_request_inbox_owner CHECK (
        (request_layout_id = 'LGNREQ01' AND owner_user_id IS NULL)
        OR (request_layout_id <> 'LGNREQ01' AND owner_user_id IS NOT NULL)),
    CONSTRAINT ck_request_inbox_operation_token CHECK (
        (request_layout_id IN ('UCRREQ01', 'USTREQ01', 'URLREQ01', 'UPWREQ01', 'ULKREQ01', 'QSBREQ01', 'NTCREQ01', 'QDLREQ01')
            AND operation_token IS NOT NULL)
        OR (request_layout_id NOT IN ('UCRREQ01', 'USTREQ01', 'URLREQ01', 'UPWREQ01', 'ULKREQ01', 'QSBREQ01', 'NTCREQ01', 'QDLREQ01')
            AND operation_token IS NULL)),
    CONSTRAINT ck_request_inbox_fingerprint CHECK (request_fingerprint_hmac ~ '^[0-9a-f]{64}$'),
    CONSTRAINT ck_request_inbox_fingerprint_key_version CHECK (
        fingerprint_key_version ~ '^[A-Za-z0-9][A-Za-z0-9._-]{0,15}$'),
    CONSTRAINT ck_request_inbox_processing_state CHECK (processing_state IN ('PROCESSING', 'COMPLETED', 'ERROR')),
    CONSTRAINT ck_request_inbox_response_layout_id CHECK (
        response_layout_id IS NULL OR response_layout_id ~ '^[A-Z0-9]{8}$'),
    CONSTRAINT ck_request_inbox_response_version CHECK (
        response_version IS NULL OR response_version ~ '^[0-9]{3}$'),
    CONSTRAINT ck_request_inbox_response_pair CHECK (
        (response_layout_id IS NULL AND response_version IS NULL)
        OR (response_layout_id IS NOT NULL AND response_version IS NOT NULL)),
    CONSTRAINT ck_request_inbox_response_snapshot_pair CHECK (
        (response_body_encrypted IS NULL AND response_key_version IS NULL)
        OR (response_body_encrypted IS NOT NULL AND octet_length(response_body_encrypted) > 28
            AND response_key_version ~ '^[A-Za-z0-9][A-Za-z0-9._-]{0,15}$')),
    CONSTRAINT ck_request_inbox_result_reference CHECK (
        (result_ref_type IS NULL AND result_ref_id IS NULL AND result_ref_uuid IS NULL)
        OR (result_ref_type = 'NONE' AND result_ref_id IS NULL AND result_ref_uuid IS NULL)
        OR (result_ref_type = 'AUTH_SESSION' AND result_ref_id IS NULL AND result_ref_uuid IS NOT NULL)
        OR (result_ref_type IN ('USER', 'QUESTION', 'JOB', 'SCENARIO_FILE')
            AND result_ref_id BETWEEN 1 AND 999999999999 AND result_ref_uuid IS NULL)),
    CONSTRAINT ck_request_inbox_state_fields CHECK (
        (processing_state = 'PROCESSING' AND completed_at IS NULL AND result_ref_type IS NULL
            AND result_ref_id IS NULL AND result_ref_uuid IS NULL AND response_layout_id IS NULL
            AND response_version IS NULL AND response_body_encrypted IS NULL AND response_key_version IS NULL)
        OR (processing_state IN ('COMPLETED', 'ERROR') AND completed_at IS NOT NULL
            AND result_ref_type IS NOT NULL AND response_layout_id IS NOT NULL AND response_version IS NOT NULL)),
    CONSTRAINT ck_request_inbox_time_order CHECK (
        created_at < expires_at AND (completed_at IS NULL OR created_at <= completed_at))
);

