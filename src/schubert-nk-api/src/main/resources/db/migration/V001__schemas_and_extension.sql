-- NK-DAT-001 / PT-DB-001,002,012 / UI 241 / SS 331 section 3, 343 section 9.2
-- Flyway creates the history schema before V001; transfer it to the non-login owner immediately.
ALTER SCHEMA schubert_meta OWNER TO nk_owner;
SET ROLE nk_owner;

CREATE SCHEMA schubert AUTHORIZATION nk_owner;
CREATE SCHEMA schubert_web_session AUTHORIZATION nk_owner;
CREATE EXTENSION IF NOT EXISTS pg_trgm WITH SCHEMA public;
REVOKE CREATE ON SCHEMA public FROM PUBLIC;

ALTER DEFAULT PRIVILEGES FOR ROLE nk_owner IN SCHEMA schubert
    REVOKE ALL ON TABLES FROM PUBLIC;
ALTER DEFAULT PRIVILEGES FOR ROLE nk_owner IN SCHEMA schubert
    REVOKE ALL ON SEQUENCES FROM PUBLIC;
ALTER DEFAULT PRIVILEGES FOR ROLE nk_owner IN SCHEMA schubert
    REVOKE ALL ON FUNCTIONS FROM PUBLIC;
ALTER DEFAULT PRIVILEGES FOR ROLE nk_owner IN SCHEMA schubert_web_session
    REVOKE ALL ON TABLES FROM PUBLIC;
ALTER DEFAULT PRIVILEGES FOR ROLE nk_owner IN SCHEMA schubert_web_session
    REVOKE ALL ON SEQUENCES FROM PUBLIC;
ALTER DEFAULT PRIVILEGES FOR ROLE nk_owner IN SCHEMA schubert_web_session
    REVOKE ALL ON FUNCTIONS FROM PUBLIC;

RESET ROLE;
