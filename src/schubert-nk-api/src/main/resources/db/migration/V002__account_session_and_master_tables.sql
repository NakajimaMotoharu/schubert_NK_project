    CONSTRAINT ck_media_assets_logical_id_bytes CHECK (octet_length(logical_id) BETWEEN 1 AND 64),
    CONSTRAINT ck_media_assets_media_type CHECK (media_type IN ('VIDEO', 'MUSIC')),
    CONSTRAINT ck_media_assets_title_bytes CHECK (octet_length(title) BETWEEN 1 AND 256),
    CONSTRAINT ck_media_assets_category_bytes CHECK (octet_length(category) BETWEEN 1 AND 64),
    CONSTRAINT ck_media_assets_section_bytes CHECK (section IS NULL OR octet_length(section) <= 128),
    CONSTRAINT ck_media_assets_storage_path_bytes CHECK (octet_length(storage_relative_path) BETWEEN 1 AND 512),
    CONSTRAINT ck_media_assets_storage_path_safe CHECK (
        storage_relative_path !~ '(^/|\\|(^|/)\.\.?(/|$)|//)'),
    CONSTRAINT ck_media_assets_display_path_bytes CHECK (octet_length(display_path) BETWEEN 1 AND 512),
    CONSTRAINT ck_media_assets_file_name_bytes CHECK (octet_length(file_name) BETWEEN 1 AND 256),
    CONSTRAINT ck_media_assets_byte_size CHECK (byte_size BETWEEN 1 AND 999999999999),
    CONSTRAINT ck_media_assets_sha256 CHECK (sha256 ~ '^[0-9a-f]{64}$'),
    CONSTRAINT ck_media_assets_mime_type CHECK (
        mime_type IN ('video/mp4', 'audio/mp4', 'audio/mpeg', 'audio/ogg', 'audio/wav', 'audio/flac')),
    CONSTRAINT ck_media_assets_pair CHECK (
        (media_type = 'VIDEO' AND pair_key IS NULL AND pair_role IS NULL)
        OR (media_type = 'MUSIC' AND (
            (pair_role IN ('M', 'I') AND octet_length(pair_key) BETWEEN 1 AND 256)
            OR (pair_role = 'N' AND pair_key IS NULL)))),
    CONSTRAINT ck_media_assets_display_order CHECK (display_order BETWEEN 1 AND 9999)
);

