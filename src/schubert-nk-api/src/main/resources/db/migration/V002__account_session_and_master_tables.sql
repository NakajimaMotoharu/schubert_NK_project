    CONSTRAINT ck_app_users_username_key_bytes CHECK (octet_length(username_key) BETWEEN 1 AND 64),
    CONSTRAINT ck_app_users_password_hash_bytes CHECK (octet_length(password_hash) BETWEEN 1 AND 255),
