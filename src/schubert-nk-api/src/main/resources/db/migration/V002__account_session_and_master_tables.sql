CREATE FUNCTION schubert.check_entry_audio_link_limit()
RETURNS trigger
LANGUAGE plpgsql
SET search_path = pg_catalog, schubert
AS $function$
BEGIN
    IF (SELECT count(*) FROM schubert.entry_audio_links
         WHERE entry_id = NEW.entry_id AND link_type = NEW.link_type) > 999 THEN
        RAISE EXCEPTION USING
            ERRCODE = '23514',
            CONSTRAINT = 'ck_entry_audio_links_entry_type_limit',
            MESSAGE = 'entry audio link count exceeds 999';
    END IF;
    RETURN NULL;
END
$function$;

CREATE CONSTRAINT TRIGGER ck_entry_audio_links_entry_type_limit
AFTER INSERT OR UPDATE OF entry_id, link_type ON schubert.entry_audio_links
DEFERRABLE INITIALLY DEFERRED
FOR EACH ROW EXECUTE FUNCTION schubert.check_entry_audio_link_limit();

