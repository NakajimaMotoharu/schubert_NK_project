CREATE TABLE schubert.auth_sessions (
    id uuid NOT NULL,
    user_id bigint NOT NULL,
    context_hash char(64) NOT NULL,
    context_ciphertext bytea NOT NULL,
    key_version varchar(16) NOT NULL,
    issued_at timestamptz NOT NULL,
    last_accessed_at timestamptz NOT NULL,
    expires_at timestamptz NOT NULL,
    revoked boolean NOT NULL DEFAULT false,
    revoked_at timestamptz,
    revoke_reason varchar(32),
    client_address inet NOT NULL,
    created_message_id uuid NOT NULL,
    CONSTRAINT pk_auth_sessions PRIMARY KEY (id),
    CONSTRAINT uq_auth_sessions_context_hash UNIQUE (context_hash),
    CONSTRAINT uq_auth_sessions_created_message_id UNIQUE (created_message_id),
    CONSTRAINT fk_auth_sessions_app_users_user_id FOREIGN KEY (user_id)
        REFERENCES schubert.app_users (id) ON DELETE RESTRICT,
    CONSTRAINT ck_auth_sessions_context_hash CHECK (context_hash ~ '^[0-9a-f]{64}$'),
    CONSTRAINT ck_auth_sessions_context_ciphertext CHECK (octet_length(context_ciphertext) > 28),
    CONSTRAINT ck_auth_sessions_key_version CHECK (key_version ~ '^[A-Za-z0-9][A-Za-z0-9._-]{0,15}$'),
    CONSTRAINT ck_auth_sessions_time_order CHECK (issued_at <= last_accessed_at AND last_accessed_at <= expires_at),
    CONSTRAINT ck_auth_sessions_revocation CHECK (
        (NOT revoked AND revoked_at IS NULL AND revoke_reason IS NULL)
        OR (revoked AND revoked_at IS NOT NULL AND revoke_reason IN
            ('LOGOUT', 'DISABLED', 'PASSWORD_RESET', 'ADMIN', 'EXPIRED', 'REPLACED')))
);

